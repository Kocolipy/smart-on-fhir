// The managed block `make fhircast-up` keeps in backend/.env: the settings
// that point a backend run by `make dev` at the local Epic stand-in
// (backend/docs/configuration/epic-login.md, "Local Epic stand-in"). Pure text
// in, text out, so scripts/fhircast-up.sh is left only the file and the
// message; write-env-block.mjs is its entry point.
//
// .env is read by bash (`set -a; source`, scripts/lib.sh's load_backend_env)
// and by docker compose, never by Spring, so a value is written the way both
// read it alike: bare when it holds only characters neither treats specially,
// else in single quotes, where a backslash stays a backslash. The signing key's
// PEM goes on one line with its breaks as a literal `\n`, which the backend
// accepts (".env.example", APP_EPIC_CLIENT_KEY).
import { generateKeyPairSync } from "node:crypto";

export const BLOCK_BEGIN = "# >>> fhircast-up (managed) >>>";
export const BLOCK_END = "# <<< fhircast-up <<<";

const KEY = "APP_EPIC_CLIENT_KEY";
const KEY_ID = "APP_EPIC_CLIENT_KEY_ID";

/**
 * Every setting the block holds, in the order it writes them. All but the
 * signing key and its id come from the caller; those two are generated once and
 * kept (see manageEnvBlock).
 */
export const MANAGED_KEYS = [
  "SPRING_PROFILES_ACTIVE",
  "APP_EPIC_ENABLED",
  "APP_EPIC_FHIR_BASE",
  "APP_EPIC_OAUTH_ISSUER",
  "APP_EPIC_CLIENT_ID",
  "APP_EPIC_REDIRECT_URI",
  KEY,
  KEY_ID,
  "APP_DEV_FIXTURES_ENABLED",
  "APP_DEV_FIXTURES_EPIC_CLINICIAN",
];

const CONFLICT = new RegExp(
  `^\\s*(?:export\\s+)?(?:${MANAGED_KEYS.join("|")})\\s*=`,
);
const NOTE =
  'commented out by make fhircast-up, whose "fhircast-up (managed)" block sets it: ';

/** A fresh EC P-384 signing key, as one line of PKCS#8 PEM with `\n` for its breaks, and its id. */
export function generateClientKey() {
  const { privateKey } = generateKeyPairSync("ec", { namedCurve: "secp384r1" });
  const pem = privateKey.export({ type: "pkcs8", format: "pem" });
  return {
    key: pem.trimEnd().replaceAll("\n", "\\n"),
    keyId: `local-${Date.now()}`,
  };
}

/** `value` as one .env word that bash and compose both read back unchanged. */
function word(value) {
  if (/^[A-Za-z0-9_@%+=:,./-]+$/.test(value)) return value;
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/** The line `name=value` of a block already written, when it holds a value. */
function held(blockLines, name) {
  const line = blockLines.find((candidate) => candidate.startsWith(`${name}=`));
  const value = line?.slice(name.length + 1).replace(/\r$/, "");
  return value && value !== "''" && value !== '""'
    ? line.replace(/\r$/, "")
    : undefined;
}

/**
 * Rewrites `.env` text so it carries the managed block and nothing else about
 * the stand-in:
 *
 *  - The block is written where it stands, or appended to a file that has none.
 *  - A line outside it that sets one of the block's settings is commented out,
 *    with a note, so the block alone decides. Every other line is left as it
 *    was, byte for byte.
 *  - The signing key and its id are generated by `newKey` only when the block
 *    holds none, and are kept after that: regenerating them would make a
 *    running backend's JWKS stale for no reason.
 *
 * `values` holds every managed setting but the key and its id. Returns the new
 * text, whether it differs from the old (the backend, which reads .env at
 * start, then needs a restart), and whether a key was generated.
 */
export function manageEnvBlock(
  text,
  values,
  { newKey = generateClientKey } = {},
) {
  for (const name of MANAGED_KEYS.filter(
    (key) => key !== KEY && key !== KEY_ID,
  )) {
    if (typeof values[name] !== "string" || values[name] === "") {
      throw new Error(`no value for ${name}`);
    }
    if (/[\r\n]/.test(values[name])) {
      throw new Error(`the value of ${name} spans lines`);
    }
  }

  const lines = text.split("\n");
  const begin = lines.findIndex((line) => line.trimEnd() === BLOCK_BEGIN);
  let end = -1;
  if (begin !== -1) {
    end = lines.findIndex(
      (line, index) => index > begin && line.trimEnd() === BLOCK_END,
    );
    if (end === -1) {
      throw new Error(
        `backend/.env opens the "${BLOCK_BEGIN}" block and never closed it with "${BLOCK_END}"`,
      );
    }
  }
  const existing = begin === -1 ? [] : lines.slice(begin + 1, end);

  let keyLine = held(existing, KEY);
  let keyIdLine = held(existing, KEY_ID);
  // A key with no id keeps the key and takes a new id; an id with no key is
  // of no use, so both are made again.
  const keyGenerated = keyLine === undefined;
  if (keyGenerated) {
    const fresh = newKey();
    keyLine = `${KEY}=${word(fresh.key)}`;
    keyIdLine = `${KEY_ID}=${word(fresh.keyId)}`;
  } else if (keyIdLine === undefined) {
    keyIdLine = `${KEY_ID}=${word(newKey().keyId)}`;
  }

  const block = [
    BLOCK_BEGIN,
    ...MANAGED_KEYS.map((name) => {
      if (name === KEY) return keyLine;
      if (name === KEY_ID) return keyIdLine;
      return `${name}=${word(values[name])}`;
    }),
    BLOCK_END,
  ];

  const outside = (rest) =>
    rest.map((line) => (CONFLICT.test(line) ? `# ${NOTE}${line}` : line));
  let result;
  if (begin === -1) {
    const body = outside(lines);
    // The split of "a\n" ends in "": drop it, then end the text on one newline.
    if (body[body.length - 1] === "") body.pop();
    result = [...body, ...(body.length > 0 ? [""] : []), ...block, ""].join(
      "\n",
    );
  } else {
    result = [
      ...outside(lines.slice(0, begin)),
      ...block,
      ...outside(lines.slice(end + 1)),
    ].join("\n");
  }
  return { text: result, changed: result !== text, keyGenerated };
}
